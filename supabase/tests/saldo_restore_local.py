"""Restore the read-only snapshot into the dedicated loopback test server only."""
import json, pathlib, re, subprocess, sys
ROOT=pathlib.Path(__file__).resolve().parents[2]
SNAP=ROOT.parent/'Respaldos/Caja_Fase2_aislada_20261104/snapshot.json'
PSQL=r'C:/Program Files/PostgreSQL/18/bin/psql.exe'
ARGS=[PSQL,'-X','-h','127.0.0.1','-p','55439','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1']
def run(sql):
 p=subprocess.run(ARGS,input=sql,encoding='utf-8',capture_output=True)
 if p.returncode: raise RuntimeError(p.stderr)
 return p.stdout
def restore():
 s=json.loads(SNAP.read_text(encoding='utf-8')); schema=s['schema']; data=s['data']
 # Fixed local database and cluster, never a configurable production connection.
 run("drop schema if exists marathon cascade; drop schema if exists auth cascade; create schema marathon; create schema auth; create schema if not exists extensions; create extension if not exists unaccent with schema extensions; do $$begin if not exists(select 1 from pg_roles where rolname='authenticated')then create role authenticated;end if;if not exists(select 1 from pg_roles where rolname='anon')then create role anon;end if;end$$; create table auth.users(id uuid primary key); create function auth.uid()returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$; create function auth.role()returns text language sql stable as $$select current_setting('request.jwt.claim.role',true)$$;")
 sql=['set check_function_bodies=off;']
 for f in schema['functions']:
  if 'FUNCTION marathon.agenda_hoy(' in f: sql.append(f+';')
 for t in schema['tables']:
  cols=[]
  for c in t['columns']:
   item='"'+c['name']+'" '+c['type']
   if c['identity']: item+=' generated by default as identity'
   elif c['default']:
    for seq in re.findall("nextval\\('([^']+)'",c['default']): sql.append('create sequence if not exists '+seq+';')
    item+=' default '+c['default']
   if c['notnull']:item+=' not null'
   cols.append(item)
  sql.append('create table marathon.'+t['name']+'('+','.join(cols)+');')
 for t in schema['tables']:
  for c in t['constraints'] or []:
   if c['type']!='f':sql.append('alter table marathon.'+t['name']+' add constraint "'+c['name']+'" '+c['ddl']+';')
 run('\n'.join(sql))
 ids=set()
 for rows in data.values():
  for row in rows:
   for k in ['user_id','actor','usuario_id','created_by','updated_by']:
    v=row.get(k)
    if v and re.fullmatch(r'[0-9a-fA-F-]{36}',str(v)):ids.add(v)
 if ids:run('insert into auth.users select value::uuid from jsonb_array_elements_text($j$'+json.dumps(sorted(ids))+'$j$::jsonb);')
 for t in schema['tables']:
  rows=data.get(t['name'],[])
  if not rows:continue
  cols=','.join('"'+c['name']+'"' for c in t['columns'])
  run('insert into marathon.'+t['name']+'('+cols+') select '+cols+' from jsonb_populate_recordset(null::marathon.'+t['name']+',$j$'+json.dumps(rows,ensure_ascii=False)+'$j$::jsonb);')
 run('set check_function_bodies=off;\n'+';\n'.join(schema['functions'])+';')
 pending=schema['views'][:]
 while pending:
  next_pending=[]
  for v in pending:
   try:run('create view marathon.'+v['name']+' as '+v['ddl']+';')
   except RuntimeError:next_pending.append(v)
  if len(next_pending)==len(pending):raise RuntimeError('Unresolved views: '+str([v['name']for v in pending]))
  pending=next_pending
 for t in schema['tables']:
  for c in t['constraints'] or []:
   if c['type']=='f':run('alter table marathon.'+t['name']+' add constraint "'+c['name']+'" '+c['ddl']+';')
 run(';\n'.join(schema['triggers'])+';')
 for t in schema['tables']:
  if t['rls']:run('alter table marathon.'+t['name']+' enable row level security;')
  for c in t['columns']:
   if c['identity'] or (c['default']and 'nextval('in c['default']):
    run("select setval(pg_get_serial_sequence('marathon."+t['name']+"','"+c['name']+"'),greatest(1,coalesce((select max(\""+c['name']+'\")from marathon.'+t['name']+"),1)),true);")
 for p in schema['policies'] or []:
  role=','.join('"'+r+'"'for r in p['roles'])
  ddl='create policy "'+p['policyname']+'" on marathon.'+p['tablename']+' as '+p['permissive']+' for '+p['cmd']+' to '+role
  if p['qual']:ddl+=' using('+p['qual']+')'
  if p['with_check']:ddl+=' with check('+p['with_check']+')'
  run(ddl+';')
 print('RESTORED',len(schema['tables']),'tables; local port 55439; production writes: 0')
if __name__=='__main__':restore()
